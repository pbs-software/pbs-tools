-- Merge #EMODES (Event modes) and #OFFLOADS
SELECT
  O.FOS_TRIP_ID AS TID_FOS,
  O.HAIL_IN_NUMBER AS HAIL, 
  CONVERT(VARCHAR, O.OFFLOAD_DATE, 20) AS OFF_DATE,
  YEAR(O.OFFLOAD_DATE) AS YEAR,
  MONTH(O.OFFLOAD_DATE) AS MONTH,
  CASE WHEN (MONTH(O.OFFLOAD_DATE) = 2 AND DAY(O.OFFLOAD_DATE) >=21) OR MONTH(O.OFFLOAD_DATE) >= 3 THEN YEAR(O.OFFLOAD_DATE)
    ELSE YEAR(O.OFFLOAD_DATE) - 1 END AS FYEAR,
  O.OFFLOAD_PORT_CODE AS PORT, 
  CONVERT(INTEGER, O.VESSEL_ID) AS VID,
  E.GEAR_MODE, 
  CONVERT(REAL, E.DEPTH_MODE) AS DEPTH_MODE, 
  E.MAJOR_MODE, E.MINOR_MODE, E.LOCAL_MODE, E.MML_MODE, E.SPP_MODE,
  O.SPECIES_CODE AS SPP_SAMP,
  CASE WHEN O.WEIGHT_UNIT_CODE = 'PND' THEN O.OFFLOAD_WEIGHT * 0.453592
    ELSE O.OFFLOAD_WEIGHT END AS OFF_WT
--  TS.NFISH, TS.NFEM, TS.NMAL, TS.NMAT, TS.NAGE, 
--  CONVERT(REAL, TS.MAGE) AS MAGE
INTO #OFFLOADS_PLUS
FROM
  #EMODES E
  INNER JOIN #OFFLOADS O ON
    E.FOS_TRIP_ID = O.FOS_TRIP_ID
ORDER BY
  O.FOS_TRIP_ID

SELECT * FROM #OFFLOADS_PLUS

