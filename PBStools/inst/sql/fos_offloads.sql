-- Get unique Trips from offloads above
SELECT
  MIN(OL.FOS_TRIP_ID) AS FOS_TRIP_ID,
--  MIN(OL.HAIL_IN_NUMBER) AS FOS_HAIL_IN,
  MIN(OL.GFB_TRIP_ID) AS GFB_TRIP_ID
INTO #OFFTRIPS
FROM #OFFLOADS OL
GROUP BY
  OL.FOS_TRIP_ID,
--  OL.HAIL_IN_NUMBER,
  OL.GFB_TRIP_ID

